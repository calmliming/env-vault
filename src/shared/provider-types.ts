/**
 * 厂商验证的结论枚举。
 *
 * 单独成文件的理由和 `env-types.ts` 一模一样：它同时被两边用到 ——
 *   - 主进程的 `providers/validate.ts`（用相对路径 import，好让 `node --test` 直接跑）
 *   - `shared/ipc.ts`（渲染层要按结论渲染状态和提示）
 * 放进 `shared/ipc.ts` 会让领域逻辑反过来依赖 IPC 契约，方向不对；
 * 各留一份又必然会漂移。
 */

/**
 * 一次验证请求的结论。
 *
 * 🔴 分成「有结论」和「没结论」两类，是这一层最重要的区分。
 * 只有前两个是**关于这把 Key 的**判断，其余五个说的都是
 * 「这次没问出答案」—— 网络不通、厂商限流、地址填错，都不代表 Key 是坏的。
 * 把它们混为一谈的后果是：用户离线时点一次验证，所有凭据被标成失效。
 *
 * 判定收敛在 `validate.ts` 的 `isConclusive()` 一处，不要在别处重写这个条件。
 */
export type ValidationOutcome =
  /** 厂商返回 2xx：这把 Key 现在能用。 */
  | 'valid'
  /** 厂商返回 401/403：明确拒绝了这把 Key。 */
  | 'invalid'
  /** 404：地址上没有这个接口，多半是调用地址填错了。和 Key 好不好无关。 */
  | 'endpoint-error'
  /** 429：被限流，这次没问出答案。 */
  | 'rate-limited'
  /** 5xx 和其它非预期状态码。厂商那边的事，不是 Key 的事。 */
  | 'provider-error'
  /** 连不上：网络、代理、DNS 或证书。 */
  | 'unreachable'
  /** 超时：请求发出去了，但在期限内没有响应。 */
  | 'timeout'
